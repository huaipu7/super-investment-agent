def macro_context(estimate: dict | None, market: str = "us") -> str:
    """把真实无风险利率渲染成提示词里的一行。

    只有 high/medium 置信度才允许模型引用该数值。低置信度就是「免费源全挂时的
    兜底常量」——那种情况下给模型一个数，等于命令它把猜测当事实写进结论。
    """
    est = estimate or {}
    value, conf = est.get("value"), est.get("confidence")
    if value is None or conf not in ("high", "medium"):
        return NO_RATE_LINE
    label = _MARKET_LABEL.get(market, "10 年期国债")
    peg = _PEG_NOTE if market == "hk" else ""
    return (f"无风险利率（{label}{peg}）为 {value:.2%}（来源：{est.get('source')}）。"
            "引用利率时只能使用该数值。")


def build_system_prompt(role: str, macro_line: str = "", as_of: str | None = None) -> str:
    """组装 system prompt：数值纪律 + 角色 + 主指令。"""
    master = (MASTER_SYSTEM_PROMPT
              .replace("{as_of}", as_of or dt.date.today().isoformat())
              .replace("{macro_context}", macro_line or NO_RATE_LINE))
    return f"{PROSE_NUMERIC_PROMPT_RULES}\n\n{role}\n\n{master}"
