"""数值纪律 —— 四个分析模块共用的硬约束。

同一段约束要出现在 SWOT / 竞品 / 地缘 / 分部四处 system prompt 里，复制四份必然漂移；
单独成模块后由 `scripts/verify_evals.py` 对文字本身做回归断言。
常量名带 `PROMPT`，是为了让 `app/observability/version.py` 把它计入 prompt_version 哈希
（它只扫描模块级 `*PROMPT*` 赋值）。
"""

PROSE_NUMERIC_PROMPT_RULES = """# ── 数值纪律（硬约束，优先于以上任何写作风格要求）──
1. 只能写上下文中已经出现过的数字。财务数据点/财务摘要/市场与竞品摘要/检索片段/DCF 结果
   （含 base_wacc、base_fair_value）里逐字可查的数值才可引用，并注明出处。
2. 禁止自行估算再给区间。不得输出「约 8.5-9.5%」「150-250bp」「提升 100-150bp」这类
   两端都不在上下文中的范围；上下文确有区间时才可引用，且两端都必须能在上下文中逐字找到。
3. 禁止编造定价。上下文中没有该产品的价格数据时，用定性表述（「千元价位」「次高端」）
   或直接写 None，不得写「600-1000 元」这类具体数字。
4. 无法量化就写「无法量化」。定量影响优先搬运已有事实（「毛利率由 2024 年 52.9% 降至
   2025 年 56.2%」），不要为了让结论显得精确而造数。
5. 资本成本只用上下文给出的 WACC；未给出时做定性判断，不得自行合成 WACC 数值。
6. 宏观利率只引用上文给出的观测值。上文写明「数据不可用」时，涉及利率的判断只做
   定性表述，不得写出联邦基金利率、基准利率、无风险利率的任何具体数值或区间。
7. 宁可少一个数字，不可多一个假数字。缺数据不算缺点，编数字才是。"""
